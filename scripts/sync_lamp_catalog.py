"""Import the Web-generated semantic catalog without maintaining a second parameter table."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--source", type=Path)
parser.add_argument("--check", action="store_true")
parser.add_argument("--board", default="apple-lamp-ov3660",
                    help="Target board directory under waveshare/ (default: apple-lamp-ov3660)")
args = parser.parse_args()
board = root / f"main/boards/waveshare/{args.board}"
source = args.source or (board / "lamp_action_catalog.v2.json")
catalog = json.loads(source.read_text(encoding="utf-8-sig"))
assert catalog["protocol_version"] == "lamp-action/2"
assert catalog["execution"] == "simulation"
assert len(catalog["primitives"]) == 13
assert catalog["limits"]["steps"] == 16
for primitive in catalog["primitives"]:
    for field in primitive["inputSchema"]["properties"].values():
        assert field["type"] in ("integer", "string")
        if field["type"] == "integer":
            assert field["minimum"] <= field["maximum"]
        else:
            assert isinstance(field["enum"], list)
text = json.dumps(catalog, ensure_ascii=False, separators=(",", ":"))
digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
header = ("// Generated by scripts/sync_lamp_catalog.py; do not edit by hand.\n"
          "#pragma once\nnamespace lamp {\n"
          f'inline constexpr const char* kCatalogSha256 = "{digest}";\n'
          'inline constexpr const char* kCatalog = R"LAMPCATALOG(' + text + ')LAMPCATALOG";\n'
          "}  // namespace lamp\n")
destination = board / "lamp_catalog.h"
if args.check:
    assert destination.read_text(encoding="utf-8") == header, "Imported catalog/header drift"
    if args.source:
        snapshot = json.loads((board / "lamp_action_catalog.v2.json").read_text(encoding="utf-8"))
        assert snapshot == catalog, "Web and firmware catalog drift"
else:
    destination.write_text(header, encoding="utf-8", newline="\n")
    (board / "lamp_action_catalog.v2.json").write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
print(f"Semantic catalog: {len(catalog['primitives'])} primitives, sha256={digest}")
